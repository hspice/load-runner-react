export const levels = [level1, level2, level3];

export function parseLevel(levelData) {
  const goldPositions = [];
  const enemySpawns = [];
  let playerSpawn = { x: 1, y: 1 };
  let exitPos = null;

  const grid = levelData.map((row, y) =>
    row.map((cell, x) => {
      switch (cell) {
        case TILE.GOLD:
          goldPositions.push({ x, y, collected: false });
          return TILE.GOLD;
        case TILE.SPAWN:
          playerSpawn = { x, y };
          return TILE.EMPTY;
        case TILE.EXIT:
          exitPos = { x, y };
          return TILE.EXIT;
        case TILE.ENEMY_SPAWN:
          enemySpawns.push({ x, y });
          return TILE.EMPTY;
        default:
          return cell;
      }
    })
  );

  return { grid, goldPositions, enemySpawns, playerSpawn, exitPos };
}
